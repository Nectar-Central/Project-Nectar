-- Friend DMs (idempotent). Apply in Supabase SQL editor.
-- Friends-only enforced server-side (accepted bngc_friends row required).
-- No edit/delete in v1 (send + read + unread counts).

create table if not exists public.bngc_messages (
  id bigint generated by default as identity primary key,
  from_discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  to_discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  body text not null,
  is_read boolean not null default false,
  created_at timestamptz not null default now(),
  constraint bngc_messages_no_self check (from_discord_id <> to_discord_id),
  constraint bngc_messages_body_len check (char_length(body) between 1 and 500)
);

create index if not exists bngc_messages_pair_idx
  on public.bngc_messages(from_discord_id, to_discord_id, created_at desc);
create index if not exists bngc_messages_to_unread_idx
  on public.bngc_messages(to_discord_id, is_read, created_at desc);

