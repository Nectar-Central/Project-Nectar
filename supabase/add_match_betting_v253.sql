-- v2.53 match betting (idempotent). Apply in Supabase SQL editor.
-- Parimutuel pools: stakes are held at bet time (deducted from nectar_coins,
-- ledger reason bet_placed); a lazy settle pass pays winners proportionally
-- (bet_won) or refunds when there is no winner (bet_refund).
-- No FK to match tables: one row covers comp / ranked-tourney / room matches.

create table if not exists public.bngc_match_bets (
  id bigint generated by default as identity primary key,
  match_key text not null, -- comp:{tid}:{ver} | rt:{tid}:{ver} | room:{rid}:{mver}
  kind text not null, -- 'comp' | 'rt' | 'room'
  tourney_id integer,
  room_id text,
  version integer not null,
  bettor_discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  pick_discord_id text not null,
  amount integer not null,
  status text not null default 'open', -- 'open' | 'won' | 'lost' | 'refunded'
  payout integer not null default 0, -- credited on win (includes returned stake)
  created_at timestamptz not null default now(),
  settled_at timestamptz,
  constraint bngc_match_bets_kind check (kind in ('comp', 'rt', 'room')),
  constraint bngc_match_bets_status check (status in ('open', 'won', 'lost', 'refunded')),
  constraint bngc_match_bets_amount check (amount >= 0)
);

create index if not exists bngc_match_bets_key_status_idx
  on public.bngc_match_bets(match_key, status);
create index if not exists bngc_match_bets_bettor_created_idx
  on public.bngc_match_bets(bettor_discord_id, created_at desc);

