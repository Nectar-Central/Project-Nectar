-- Comp system schema (idempotent). Apply in Supabase SQL editor.
-- Host-local recording pipeline banks here: stG 1 opens a match, stG 3
-- seals it (stG 2 ignored). Nothing is calculated at record time; the
-- dashboard/bot compute on demand from these raw rows.
-- Tourney IDs start at 0 (dedicated sequence).

create sequence if not exists public.bngc_comp_tourney_id_seq start with 0 increment by 1;

create table if not exists public.bngc_comp_tourneys (
  id integer primary key default nextval('public.bngc_comp_tourney_id_seq'),
  code text, -- 5-char room pID when played in a tagged room (nullable: manual tourneys)
  name text not null,
  status text not null default 'open', -- 'open' | 'closed'
  series_len integer not null default 0, -- expected match count (0 = open-ended)
  points_table jsonb not null default '{"kill":1,"win":3,"placement":[10,7,5,3,1]}'::jsonb,
  reg_channel_id text,
  board_channel_id text,
  player_role_id text,
  reg_open boolean not null default false,
  created_by text,
  created_at timestamptz not null default now(),
  constraint bngc_comp_tourneys_status check (status in ('open', 'closed'))
);

create table if not exists public.bngc_comp_matches (
  id bigint generated by default as identity primary key,
  tourney_id integer references public.bngc_comp_tourneys(id) on delete cascade,
  version integer not null, -- per-tourney match counter (0, 1, 2, ...)
  room_id text,
  status text not null default 'open', -- 'open' | 'sealed' | 'manual'
  started_at timestamptz not null default now(),
  sealed_at timestamptz,
  constraint bngc_comp_matches_status check (status in ('open', 'sealed', 'manual')),
  constraint bngc_comp_matches_ver unique (tourney_id, version)
);

create table if not exists public.bngc_comp_events (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.bngc_comp_matches(id) on delete cascade,
  etype text not null, -- 'kill' | 'knock' | 'alv' | 'leave'
  actor_nr integer,
  actor_name text,
  target_name text,
  discord_id text, -- resolved via registered game_username (nullable until mapped)
  alive boolean, -- alv snapshots only
  created_at timestamptz not null default now(),
  constraint bngc_comp_events_type check (etype in ('kill', 'knock', 'alv', 'leave'))
);

create table if not exists public.bngc_comp_registrations (
  id bigint generated by default as identity primary key,
  tourney_id integer not null references public.bngc_comp_tourneys(id) on delete cascade,
  team_label text,
  member_ids text[] not null default '{}',
  captain_id text,
  source_message_id text,
  status text not null default 'pending', -- 'pending' | 'accepted' | 'rejected' | 'banned'
  created_at timestamptz not null default now(),
  constraint bngc_comp_reg_status check (status in ('pending', 'accepted', 'rejected', 'banned')),
  constraint bngc_comp_reg_team_size check (array_length(member_ids, 1) between 1 and 2),
  constraint bngc_comp_reg_msg unique (tourney_id, source_message_id)
);

create table if not exists public.bngc_comp_results (
  match_id bigint primary key references public.bngc_comp_matches(id) on delete cascade,
  standings jsonb not null default '[]'::jsonb, -- [{discord_id, name, kills, placement, points}]
  computed_at timestamptz not null default now(),
  computed_by text
);

create index if not exists bngc_comp_events_match_idx
  on public.bngc_comp_events(match_id, id);
create index if not exists bngc_comp_matches_tourney_idx
  on public.bngc_comp_matches(tourney_id, version);
create index if not exists bngc_comp_reg_tourney_idx
  on public.bngc_comp_registrations(tourney_id, status);

