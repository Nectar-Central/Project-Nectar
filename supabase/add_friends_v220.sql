-- Friends + party invites (idempotent). Apply in Supabase SQL editor.
-- v1 scope: request / accept / decline / remove, party invite + join.
-- No block in v1. Discord-registered users only (discord_id keys).

create table if not exists public.bngc_friends (
  id bigint generated by default as identity primary key,
  requester_discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  addressee_discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  status text not null default 'pending', -- 'pending' | 'accepted'
  created_at timestamptz not null default now(),
  constraint bngc_friends_no_self check (requester_discord_id <> addressee_discord_id),
  constraint bngc_friends_status check (status in ('pending', 'accepted')),
  constraint bngc_friends_pair unique (requester_discord_id, addressee_discord_id)
);

create table if not exists public.bngc_party_invites (
  id bigint generated by default as identity primary key,
  code text not null, -- 5-char private pID the recipient types in-game
  from_discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  to_discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  constraint bngc_party_no_self check (from_discord_id <> to_discord_id)
);

create index if not exists bngc_friends_addressee_idx
  on public.bngc_friends(addressee_discord_id, status);
create index if not exists bngc_friends_requester_idx
  on public.bngc_friends(requester_discord_id, status);
create index if not exists bngc_party_invites_to_idx
  on public.bngc_party_invites(to_discord_id, expires_at);

