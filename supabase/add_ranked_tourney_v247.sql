-- Ranked tourneys (v247): independent clone of the comp schema (v226–v239
-- consolidated) under bngc_ranked_tourney_* names, plus Elo snapshot/history.
-- Display-only Elo: points math is identical to comp; Elo is shown in the
-- dashboard and never changes scores. Idempotent — safe to run more than once.
--
-- Existing ranked-room tables (ranked_rooms, ranked_results,
-- bngc_ranked_matches, bngc_ranked_events) are untouched; the userscript
-- seal economy keeps using those.

create sequence if not exists public.bngc_ranked_tourney_id_seq start with 0 increment by 1;

create table if not exists public.bngc_ranked_tourneys (
  id integer primary key default nextval('public.bngc_ranked_tourney_id_seq'),
  code text,
  name text not null,
  status text not null default 'created',
  mode text not null default 'solo',
  series_len integer not null default 0,
  points_table jsonb not null default '{"kill":1,"win":3,"placement":[10,7,5,3,1]}'::jsonb,
  reg_channel_id text,
  board_channel_id text,
  player_role_id text,
  reg_open boolean not null default false,
  created_by text,
  created_at timestamptz not null default now(),
  scheduled_at timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  game_mode text,
  region text not null default 'EU',
  rules_channel_id text,
  shoot_timer text not null default '4:30',
  announce_channel_id text,
  announce_message_id text,
  ping_role_id text,
  max_players integer not null default 0,
  host_playing boolean not null default true,
  hosts text[] not null default '{}',
  -- Elo snapshot (display-only): start_elo seeds every participant, avg_elo
  -- is the mean of the per-player elo rows (null until first registration).
  start_elo integer not null default 1000,
  avg_elo numeric,
  elo_k integer not null default 32,
  constraint bngc_ranked_tourneys_status check (status in ('created', 'scheduled', 'started', 'ended')),
  constraint bngc_ranked_tourneys_mode check (mode in ('solo', 'duo'))
);

create table if not exists public.bngc_ranked_tourney_matches (
  id bigint generated by default as identity primary key,
  tourney_id integer references public.bngc_ranked_tourneys(id) on delete cascade,
  version integer not null,
  room_id text,
  status text not null default 'open',
  winner_discord_id text,
  placements jsonb not null default '{}'::jsonb,
  point_awards jsonb not null default '{}'::jsonb,
  removed_discord_ids jsonb not null default '[]'::jsonb,
  started_at timestamptz not null default now(),
  sealed_at timestamptz,
  constraint bngc_ranked_tourney_matches_status check (status in ('open', 'sealed', 'manual')),
  constraint bngc_ranked_tourney_matches_ver unique (tourney_id, version)
);

create table if not exists public.bngc_ranked_tourney_events (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.bngc_ranked_tourney_matches(id) on delete cascade,
  etype text not null,
  actor_nr integer,
  actor_name text,
  target_name text,
  discord_id text,
  alive boolean,
  manual boolean not null default false,
  created_at timestamptz not null default now(),
  constraint bngc_ranked_tourney_events_type check (etype in ('kill', 'knock', 'alv', 'leave'))
);

create table if not exists public.bngc_ranked_tourney_registrations (
  id bigint generated by default as identity primary key,
  tourney_id integer not null references public.bngc_ranked_tourneys(id) on delete cascade,
  team_label text,
  member_ids text[] not null default '{}',
  member_names jsonb not null default '{}',
  team_color text,
  captain_id text,
  source_message_id text,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  constraint bngc_ranked_tourney_reg_status check (status in ('pending', 'accepted', 'rejected', 'banned')),
  constraint bngc_ranked_tourney_reg_team_size check (array_length(member_ids, 1) between 1 and 2),
  constraint bngc_ranked_tourney_reg_msg unique (tourney_id, source_message_id)
);

create table if not exists public.bngc_ranked_tourney_results (
  match_id bigint primary key references public.bngc_ranked_tourney_matches(id) on delete cascade,
  standings jsonb not null default '[]'::jsonb,
  computed_at timestamptz not null default now(),
  computed_by text
);

create table if not exists public.bngc_ranked_tourney_adjustments (
  id bigserial primary key,
  tourney_id integer not null references public.bngc_ranked_tourneys(id) on delete cascade,
  match_id integer references public.bngc_ranked_tourney_matches(id) on delete set null,
  discord_id text not null,
  delta_points integer not null,
  reason text not null default '',
  created_by text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.bngc_ranked_tourney_pr_history (
  tourney_id integer not null references public.bngc_ranked_tourneys(id) on delete cascade,
  discord_id text not null,
  pr numeric not null,
  kills integer not null default 0,
  wins integer not null default 0,
  matches integer not null default 0,
  avg_placement numeric,
  players numeric not null default 0,
  manual boolean not null default false,
  computed_at timestamptz not null default now(),
  primary key (tourney_id, discord_id)
);

-- Per-player Elo snapshot per tourney (display-only). One row per
-- (tourney, player), seeded at start_elo on first sight; elo_after stays
-- equal to elo_before until a future Elo engine writes deltas.
create table if not exists public.bngc_ranked_tourney_elo (
  tourney_id integer not null references public.bngc_ranked_tourneys(id) on delete cascade,
  discord_id text not null,
  elo_before numeric not null default 1000,
  elo_after numeric not null default 1000,
  matches integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (tourney_id, discord_id)
);

create index if not exists bngc_ranked_tourney_events_match_idx
  on public.bngc_ranked_tourney_events(match_id, id);
create index if not exists bngc_ranked_tourney_matches_tourney_idx
  on public.bngc_ranked_tourney_matches(tourney_id, version);
create index if not exists bngc_ranked_tourney_reg_tourney_idx
  on public.bngc_ranked_tourney_registrations(tourney_id, status);
create index if not exists bngc_ranked_tourney_adjustments_tourney_idx
  on public.bngc_ranked_tourney_adjustments (tourney_id);
create index if not exists bngc_ranked_tourney_adjustments_player_idx
  on public.bngc_ranked_tourney_adjustments (tourney_id, discord_id);
create index if not exists bngc_ranked_tourney_pr_history_discord_idx
  on public.bngc_ranked_tourney_pr_history (discord_id);
create index if not exists bngc_ranked_tourney_elo_discord_idx
  on public.bngc_ranked_tourney_elo (discord_id);

