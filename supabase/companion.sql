insert into storage.buckets (id, name, public) values ('lobby-music','lobby-music', true) on conflict (id) do nothing;

-- Alert inbox for bot DMs: login / locked / cheat / warning / blacklist
create table if not exists public.bngc_alerts (
  id bigint generated by default as identity primary key,
  discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  alert_type text not null, -- login | locked | cheat | warning | blacklist
  country text,
  ip_address text,
  game_username text,
  game_id text,
  discord_username text,
  details jsonb not null default '{}'::jsonb,
  severity text not null default 'info',
  is_read boolean not null default false,
  notified boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists bngc_login_tokens_discord_id_idx
  on public.bngc_login_tokens(discord_id);
create index if not exists bngc_sessions_discord_id_active_idx
  on public.bngc_sessions(discord_id, is_active, created_at desc);
create index if not exists bngc_game_events_session_created_idx
  on public.bngc_game_events(session_id, created_at);
create index if not exists bngc_game_events_discord_created_idx
  on public.bngc_game_events(discord_id, created_at);
create index if not exists bngc_alerts_discord_notified_idx
  on public.bngc_alerts(discord_id, notified, created_at desc);
create index if not exists bngc_alerts_type_idx
  on public.bngc_alerts(alert_type, created_at desc);

