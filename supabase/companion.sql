-- Supabase schema for the active companion bot and its game-data commands.
-- Apply this in the connected Supabase project's SQL editor.

create table if not exists public.players (
  id text primary key,
  username text not null,
  display_name text not null,
  game_handle text not null,
  avatar_url text,
  registered_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bngc_users (
  discord_id text primary key,
  discord_username text not null,
  token text unique not null,
  game_username text,
  game_id text,
  skin text,
  pickaxe text,
  kills integer not null default 0,
  deaths integer not null default 0,
  wins integer not null default 0,
  defeats integer not null default 0,
  playtime_global integer not null default 0,
  playtime_per_gm text not null default '{}',
  first_seen boolean not null default true,
  is_locked boolean not null default false,
  lock_reason text,
  locked_at timestamptz,
  locked_ip text,
  -- two-tier lockout: default (user can /unlock) vs admin (only admin can unlock)
  lock_scope text not null default 'default', -- 'default' | 'admin'
  is_admin_locked boolean not null default false,
  registered_at timestamptz not null default now(),
  last_seen timestamptz
);

create table if not exists public.bngc_login_tokens (
  token text primary key,
  discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  expires_at timestamptz not null,
  used boolean not null default false,
  used_at timestamptz,
  used_ip text
);

create table if not exists public.bngc_sessions (
  session_id text primary key,
  discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  created_at timestamptz not null default now(),
  is_active boolean not null default true,
  session_key text,
  req_secret text,
  current_token text,
  token_counter integer not null default 0,
  last_used_at timestamptz
);

create table if not exists public.bngc_game_events (
  id bigint generated by default as identity primary key,
  session_id text not null references public.bngc_sessions(session_id) on delete cascade,
  discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  event_type text not null,
  event_data jsonb not null default '{}'::jsonb,
  is_valid boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.bngc_player_stats (
  discord_id text primary key references public.bngc_users(discord_id) on delete cascade,
  kills integer not null default 0,
  deaths integer not null default 0,
  wins integer not null default 0,
  defeats integer not null default 0
);

create table if not exists public.bngc_security_logs (
  id bigint generated by default as identity primary key,
  discord_id text,
  event_type text not null,
  ip_address text,
  details jsonb not null default '{}'::jsonb,
  severity text not null default 'info',
  created_at timestamptz not null default now()
);

