-- Supabase schema for the active companion bot and its game-data commands.
-- Apply this in the connected Supabase project's SQL editor.

create table if not exists public.bngc_users (
  discord_id text primary key,
  discord_username text not null,
  token text unique not null,
  game_username text,
  game_id text,
  skin text,
  pickaxe text,
  kills integer not null default 0,
  deaths integer not null default 0,
  wins integer not null default 0,
  defeats integer not null default 0,
  playtime_global integer not null default 0,
  playtime_per_gm text not null default '{}',
  first_seen boolean not null default true,
  is_locked boolean not null default false,
  lock_reason text,
  locked_at timestamptz,
  locked_ip text,
  registered_at timestamptz not null default now(),
  last_seen timestamptz
);

create table if not exists public.bngc_login_tokens (
  token text primary key,
  discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  expires_at timestamptz not null,
  used boolean not null default false,
  used_at timestamptz,
  used_ip text
);

create table if not exists public.bngc_sessions (
  session_id text primary key,
  discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  created_at timestamptz not null default now(),
  is_active boolean not null default true
);

create table if not exists public.bngc_game_events (
  id bigint generated by default as identity primary key,
  session_id text not null references public.bngc_sessions(session_id) on delete cascade,
  discord_id text not null references public.bngc_users(discord_id) on delete cascade,
  event_type text not null,
  event_data jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.bngc_player_stats (
  discord_id text primary key references public.bngc_users(discord_id) on delete cascade,
  kills integer not null default 0,
  deaths integer not null default 0,
  wins integer not null default 0,
  defeats integer not null default 0
);

create table if not exists public.bngc_security_logs (
  id bigint generated by default as identity primary key,
  discord_id text,
  event_type text not null,
  ip_address text,
  details jsonb not null default '{}'::jsonb,
  severity text not null default 'info',
  created_at timestamptz not null default now()
);

create index if not exists bngc_login_tokens_discord_id_idx
  on public.bngc_login_tokens(discord_id);
create index if not exists bngc_sessions_discord_id_active_idx
  on public.bngc_sessions(discord_id, is_active, created_at desc);
create index if not exists bngc_game_events_session_created_idx
  on public.bngc_game_events(session_id, created_at);
create index if not exists bngc_game_events_discord_created_idx
  on public.bngc_game_events(discord_id, created_at);

alter table public.bngc_users enable row level security;
alter table public.bngc_login_tokens enable row level security;
alter table public.bngc_sessions enable row level security;
alter table public.bngc_game_events enable row level security;
alter table public.bngc_player_stats enable row level security;
alter table public.bngc_security_logs enable row level security;

